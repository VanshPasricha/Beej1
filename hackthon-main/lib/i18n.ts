export type Language = keyof typeof translations
export type TranslationKey = keyof typeof translations.en

export function getTranslation(language: Language, key: TranslationKey): string {
  // Narrow the locale dict so TS knows the keys match the English shape (may be partial)
  const dict = translations[language] as Partial<typeof translations.en> | undefined
  const value = (dict?.[key] ?? translations.en[key]) as unknown
  return typeof value === "string" ? value : (key as string)
}

export function getCurrentLanguage(): Language {
  if (typeof window !== "undefined") {
    const saved = localStorage.getItem("beejsetu-language") as Language
    return saved || "en"
  }
  return "en"
}
